CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL,
    enabled BOOLEAN NOT NULL,
    failed_login_attempts INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE scan_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    scan_type VARCHAR(20) NOT NULL,
    input_hash VARCHAR(64) NOT NULL,
    input_summary VARCHAR(2048),
    prediction VARCHAR(30) NOT NULL,
    risk_category VARCHAR(20) NOT NULL,
    risk_score INTEGER NOT NULL,
    model_version VARCHAR(50) NOT NULL,
    scanned_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_scan_history_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE threat_indicators (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id BIGINT NOT NULL,
    description VARCHAR(300) NOT NULL,
    CONSTRAINT fk_threat_indicators_scan FOREIGN KEY (scan_id) REFERENCES scan_history (id)
);

CREATE TABLE model_registry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_version VARCHAR(50) NOT NULL UNIQUE,
    model_type VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL,
    registered_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100),
    action VARCHAR(100) NOT NULL,
    details VARCHAR(500),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
