package com.phishguard.database;

import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;

class FlywayMigrationTests {

    @Test
    void baselinesExistingSchemaAndAddsLockoutExpiryWithoutLosingData() throws Exception {
        String databaseName = "phishguard_migration_" + UUID.randomUUID().toString().replace("-", "");
        String url = "jdbc:h2:mem:" + databaseName + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1";

        try (Connection connection = DriverManager.getConnection(url, "sa", "");
             Statement statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE users (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        username VARCHAR(100) NOT NULL UNIQUE,
                        email VARCHAR(254) NOT NULL UNIQUE,
                        password_hash VARCHAR(100) NOT NULL,
                        role VARCHAR(20) NOT NULL,
                        enabled BOOLEAN NOT NULL,
                        failed_login_attempts INTEGER NOT NULL,
                        created_at TIMESTAMP WITH TIME ZONE NOT NULL
                    )
                    """);
            statement.execute("""
                    INSERT INTO users
                        (username, email, password_hash, role, enabled, failed_login_attempts, created_at)
                    VALUES
                        ('preserved-user', 'preserved@example.test', 'test-hash', 'USER', TRUE, 0, CURRENT_TIMESTAMP)
                    """);
        }

        Flyway flyway = Flyway.configure()
                .dataSource(url, "sa", "")
                .baselineOnMigrate(true)
                .baselineVersion("1")
                .load();

        assertEquals(1, flyway.migrate().migrationsExecuted);
        assertEquals(0, flyway.migrate().migrationsExecuted);

        try (Connection connection = DriverManager.getConnection(url, "sa", "");
             Statement statement = connection.createStatement();
             ResultSet resultSet = statement.executeQuery(
                     "SELECT username, locked_until FROM users WHERE email = 'preserved@example.test'")) {
            resultSet.next();
            assertEquals("preserved-user", resultSet.getString("username"));
            assertNull(resultSet.getObject("locked_until"));
        }
    }
}
